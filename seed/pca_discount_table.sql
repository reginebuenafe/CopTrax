    discount_id     SERIAL PRIMARY KEY,
    moisture_content_pct DECIMAL(4,1) NOT NULL UNIQUE,
    discount_value  DECIMAL(4,1) NOT NULL,
    table_version   VARCHAR(20) DEFAULT 'NEW PCA TABLE',
    effective_date  DATE DEFAULT CURRENT_DATE
);

